// Command acpgen writes this module's Go code from ACP's JSON schema: the
// types (types_gen.go) and the methods (methods_gen.go) of a package.
//
//	acpgen -schema schema.json -meta meta.json -pkg acp -out .
//
// The schema's release is read from VERSION, beside it.
//
// With -copy, it also copies the hand-written files of the package in that
// folder (the connection, the agent and client sides, their tests) into
// -out with the package renamed, so a package generated from another
// schema (the unstable one) has the same API. `make generate` runs it for
// both packages; `make schema` fetches the pinned schema first.
//
// How the schema becomes Go:
//
//   - an object is a struct; an optional field is left out when empty, and
//     held by pointer when it is a struct or a number (whose zero means
//     something); a required list left nil is sent as [];
//   - fields the schema marks x-deserialize-default-on-error (or
//     x-deserialize-skip-invalid-items) decode leniently: a bad value is
//     dropped instead of failing the whole message;
//   - a union with a tag property (sessionUpdate, type, ...) is a struct
//     with the tag, one field per variant (a pointer, or a bool for a
//     variant with no fields), and Other, which keeps an unknown variant
//     whole; other unions of objects are told apart by their required
//     properties, unions of values by their JSON kind;
//   - a union of string or integer constants is a named type with
//     constants;
//   - a field whose null means something other than its absence (a title
//     an update clears) is a Nullable.
//
// The methods come from the x-method and x-side of each request type, in
// meta.json's order: the Agent and Client interfaces, their Unimplemented
// types, the dispatch of incoming messages, and the AgentConn and
// ClientConn calls.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	schemaFile := flag.String("schema", "", "the schema (schema.json)")
	metaFile := flag.String("meta", "", "the method names (meta.json)")
	pkg := flag.String("pkg", "acp", "the package to write")
	out := flag.String("out", ".", "the folder to write to")
	copyFrom := flag.String("copy", "", "a folder whose hand-written files to copy into -out")
	flag.Parse()
	if *schemaFile == "" || *metaFile == "" {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(*schemaFile, *metaFile, *pkg, *out, *copyFrom); err != nil {
		log.Fatal(err)
	}
}

func run(schemaFile, metaFile, pkg, out, copyFrom string) error {
	raw, err := os.ReadFile(schemaFile)
	if err != nil {
		return err
	}
	v, err := os.ReadFile(filepath.Join(filepath.Dir(schemaFile), "VERSION"))
	if err != nil {
		return err
	}
	version := strings.TrimSpace(string(v))
	meta, err := os.ReadFile(metaFile)
	if err != nil {
		return err
	}
	s, err := loadSchema(raw)
	if err != nil {
		return err
	}
	m, err := newModel(s, pkg)
	if err != nil {
		return err
	}
	ms, err := methods(m, meta)
	if err != nil {
		return err
	}
	from := filepath.Base(schemaFile)
	var types bytes.Buffer
	header(&types, from, version, pkg, `"encoding/json"`)
	genTypes(&types, m)
	if err := write(filepath.Join(out, "types_gen.go"), types.Bytes()); err != nil {
		return err
	}
	var calls bytes.Buffer
	header(&calls, from, version, pkg, `"context"`, `"encoding/json"`)
	fmt.Fprintf(&calls, "// SchemaVersion is the release of ACP's schema this package follows.\nconst SchemaVersion = %q\n\n", version)
	genMethods(&calls, m, ms)
	if err := write(filepath.Join(out, "methods_gen.go"), calls.Bytes()); err != nil {
		return err
	}
	if copyFrom != "" {
		return copyPackage(copyFrom, out, pkg)
	}
	return nil
}

func header(b *bytes.Buffer, from, version, pkg string, imports ...string) {
	fmt.Fprintf(b, "// Code generated by acpgen from ACP's %s, release %s. DO NOT EDIT.\n\npackage %s\n\nimport (\n", from, version, pkg)
	for _, i := range imports {
		b.WriteString("\t" + i + "\n")
	}
	b.WriteString(")\n\n")
}

func write(path string, src []byte) error {
	formatted, err := format.Source(src)
	if err != nil {
		_ = os.WriteFile(path, src, 0o600) // unformatted, to look at; the format error is the one to report
		return fmt.Errorf("%s: %w", path, err)
	}
	return os.WriteFile(path, formatted, 0o644)
}
