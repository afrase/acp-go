package main

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const copiedMark = "// Code generated by acpgen from ../"

// rootOnly are the tests that aren't copied: they test the connection,
// the processes and the README, whose code is the same in every copy, so a
// copy would run the same tests again. The copied tests (the types, the
// methods' routing and their checks, the examples) use harness_test.go.
var rootOnly = map[string]bool{
	"bench_test.go":                    true,
	"conn_owed_test.go":                true,
	"conn_test.go":                     true,
	"export_test.go":                   true,
	"log_test.go":                      true,
	"process_test.go":                  true,
	"process_tree_test.go":             true,
	"process_unix_internal_test.go":    true,
	"process_unix_test.go":             true,
	"process_windows_internal_test.go": true,
	"process_windows_test.go":          true,
	"readme_test.go":                   true,
	"stdio_unix_test.go":               true,
}

var (
	packageLine = regexp.MustCompile(`(?m)^package acp(_test)?$`)
	moduleLine  = regexp.MustCompile(`(?m)^module (\S+)\r?$`)
)

// copyPackage copies package acp's hand-written files in from (all but
// doc.go, the generated ones and the rootOnly tests) into out as package
// pkg, so the package generated there from another schema has the same
// connection and sides, and the tests of what depends on the schema. Copies whose source is gone are removed.
func copyPackage(from, out, pkg string) error {
	gomod, err := os.ReadFile(filepath.Join(from, "go.mod"))
	if err != nil {
		return err
	}
	mod := moduleLine.FindSubmatch(gomod)
	if mod == nil {
		return errors.New("no module line in go.mod")
	}
	modPath := string(mod[1])
	sources, err := filepath.Glob(filepath.Join(from, "*.go"))
	if err != nil {
		return err
	}
	kept := map[string]bool{}
	for _, src := range sources {
		name := filepath.Base(src)
		b, err := os.ReadFile(src)
		if err != nil {
			return err
		}
		if name == "doc.go" || rootOnly[name] || bytes.HasPrefix(b, []byte("// Code generated")) {
			continue
		}
		if !packageLine.Match(b) {
			return fmt.Errorf("%s: not package acp", src)
		}
		b = packageLine.ReplaceAllFunc(b, func(line []byte) []byte {
			if bytes.HasSuffix(line, []byte("_test")) {
				return []byte("package " + pkg + "_test")
			}
			return []byte("package " + pkg)
		})
		b = bytes.ReplaceAll(b, []byte(`"`+modPath+`"`), []byte(`acp "`+modPath+"/"+pkg+`"`))
		b = append([]byte(copiedMark+name+". DO NOT EDIT.\n\n"), b...)
		dst := filepath.Join(out, name)
		if prev, err := os.ReadFile(dst); err == nil && !bytes.HasPrefix(prev, []byte(copiedMark)) {
			return fmt.Errorf("%s is hand-written: it would be overwritten by a copy of %s", dst, src)
		}
		if err := write(dst, b); err != nil {
			return err
		}
		kept[name] = true
	}
	old, err := filepath.Glob(filepath.Join(out, "*.go"))
	if err != nil {
		return err
	}
	for _, f := range old {
		b, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		if strings.HasPrefix(string(b), copiedMark) && !kept[filepath.Base(f)] {
			if err := os.Remove(f); err != nil {
				return err
			}
		}
	}
	return nil
}
