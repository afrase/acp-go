package main

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const copiedMark = "// Code generated by acpgen from ../"

var (
	packageLine = regexp.MustCompile(`(?m)^package acp(_test)?$`)
	moduleLine  = regexp.MustCompile(`(?m)^module (\S+)$`)
)

// copyPackage copies package acp's hand-written files in from (all but
// doc.go and the generated ones) into out as package pkg, so the package
// generated there from another schema has the same connection, sides and
// tests. Copies whose source is gone are removed.
func copyPackage(from, out, pkg string) error {
	gomod, err := os.ReadFile(filepath.Join(from, "go.mod"))
	if err != nil {
		return err
	}
	mod := moduleLine.FindSubmatch(gomod)
	if mod == nil {
		return errors.New("no module line in go.mod")
	}
	modPath := string(mod[1])
	sources, err := filepath.Glob(filepath.Join(from, "*.go"))
	if err != nil {
		return err
	}
	kept := map[string]bool{}
	for _, src := range sources {
		name := filepath.Base(src)
		b, err := os.ReadFile(src)
		if err != nil {
			return err
		}
		if name == "doc.go" || bytes.HasPrefix(b, []byte("// Code generated")) {
			continue
		}
		if !packageLine.Match(b) {
			return fmt.Errorf("%s: not package acp", src)
		}
		b = packageLine.ReplaceAllFunc(b, func(line []byte) []byte {
			if bytes.HasSuffix(line, []byte("_test")) {
				return []byte("package " + pkg + "_test")
			}
			return []byte("package " + pkg)
		})
		b = bytes.ReplaceAll(b, []byte(`"`+modPath+`"`), []byte(`acp "`+modPath+"/"+pkg+`"`))
		b = append([]byte(copiedMark+name+". DO NOT EDIT.\n\n"), b...)
		dst := filepath.Join(out, name)
		if prev, err := os.ReadFile(dst); err == nil && !bytes.HasPrefix(prev, []byte(copiedMark)) {
			return fmt.Errorf("%s is hand-written: it would be overwritten by a copy of %s", dst, src)
		}
		if err := write(dst, b); err != nil {
			return err
		}
		kept[name] = true
	}
	old, err := filepath.Glob(filepath.Join(out, "*.go"))
	if err != nil {
		return err
	}
	for _, f := range old {
		b, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		if strings.HasPrefix(string(b), copiedMark) && !kept[filepath.Base(f)] {
			if err := os.Remove(f); err != nil {
				return err
			}
		}
	}
	return nil
}
